const stopWordsPattern = new RegExp(
  `\\b(?:${Array.from(new Set(rawStopWords.map(unaccentize)))
    .sort((left, right) => right.length - left.length)
    .map(escapeRegExp)
    .join('|')})\\b`,
  'gi'
)

export const toContentSlug = (string: string): string => {
  if (!string || string.length === 0) {
    return ''
  }

  let result = unaccentize(string.toLowerCase().trim().replaceAll('_', ' '))
  result = result.replace(stopWordsPattern, '')

  return convert(result).slice(0, 150).replace(/-+$/g, '')
}
